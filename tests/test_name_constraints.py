# ---------------------------------------------------------------------------
# Unit-level semantics of the tree containment checkers
# ---------------------------------------------------------------------------


def test_dns_subtree_boundary_unit():
    # dNSName constraints use label-wise suffix matching (RFC 5280 4.2.1.10):
    # the base itself and anything below it matches, string suffixes that
    # are not label boundaries do not.
    assert dns_tree_contains('sub.example.com', 'sub.example.com')
    assert dns_tree_contains('sub.example.com', 'www.sub.example.com')
    assert dns_tree_contains('sub.example.com', 'a.b.sub.example.com')
    assert not dns_tree_contains('sub.example.com', 'evilsub.example.com')
    assert not dns_tree_contains('sub.example.com', 'sub.example.com.evil.net')
    assert not dns_tree_contains('sub.example.com', 'example.com')


def test_email_vs_domain_constraint_unit():
    # rfc822Name host form: matches mailboxes at exactly that host,
    # not at sub-hosts (unlike dNSName subtree semantics).
    assert email_tree_contains('sub.example.com', 'user@sub.example.com')
    assert not email_tree_contains('sub.example.com', 'user@deep.sub.example.com')
    # rfc822Name domain form (leading dot): matches sub-hosts, but not
    # the bare host itself.
    assert email_tree_contains('.example.com', 'user@mail.example.com')
    assert not email_tree_contains('.example.com', 'user@example.com')
    # rfc822Name mailbox form: exact mailbox match only.
    assert email_tree_contains('admin@example.com', 'admin@example.com')
    assert not email_tree_contains('admin@example.com', 'admin@mail.example.com')
    assert not email_tree_contains('admin@example.com', 'root@example.com')


def test_uri_malformed_is_not_an_ordinary_mismatch():
    # A well-formed URI outside the permitted host tree is an ordinary
    # mismatch (checker returns False) ...
    assert not uri_tree_contains('.example.com', 'https://example.org/x')
    assert uri_tree_contains('.example.com', 'https://www.example.com/x')
    # ... but a URI without a parseable host is malformed and must raise,
    # so callers can fail closed instead of treating it as a non-match.
    with pytest.raises(NameConstraintError):
        uri_tree_contains('.example.com', 'notauri')


def test_empty_subtree_base_unit():
    # An empty dNSName base is not the same as "no constraint":
    # as a permitted subtree it permits nothing ...
    assert not dns_tree_contains('', 'www.example.com')
    empty_tree = NameSubtree.from_name(GeneralNameType.DNS_NAME, '')
    assert 'www.example.com' not in empty_tree
    # ... and as an excluded subtree it only "excludes" the empty name
    # itself, which never occurs as a real dNSName, so in practice it
    # excludes nothing.
    assert dns_tree_contains('', '')


def test_unsupported_general_name_types_fail_loudly():
    # iPAddress constraints (incl. masks) are not implemented; containment
    # checks must raise rather than silently accept or reject.
    ip_tree = NameSubtree.from_name(GeneralNameType.IP_ADDRESS, b'\x0a\x00\x00\x00')
    with pytest.raises(NotImplementedError):
        _ = 'whatever' in ip_tree
    # minimum/maximum on a GeneralSubtree are not meaningful in the PKIX
    # profile; they must also fail loudly instead of being ignored.
    tree_with_min = NameSubtree(
        name_type=GeneralNameType.DNS_NAME,
        tree_base=name_trees._StringOrName('example.com'),
        min=1,
    )
    with pytest.raises(NotImplementedError):
        _ = 'www.example.com' in tree_with_min


