@pytest.mark.asyncio
async def test_valid_leaf_with_multiple_sans(chain, val_ctx):
    # manual derivation:
    #  www.sub.example.com  ∈ example.com (ICA-1) ∩ sub.example.com (ICA-2)
    #  user@sub.example.com ∈ .example.com (ICA-1) ∩ sub.example.com (ICA-2)
    #  https://www.sub.example.com/x has host www.sub.example.com ∈ .example.com
    #  none of the three names hits an excluded subtree
    leaf = _issue_leaf(
        issuer=chain.ica2,
        san=[
            crypto_x509.DNSName('www.sub.example.com'),
            crypto_x509.RFC822Name('user@sub.example.com'),
            crypto_x509.UniformResourceIdentifier(
                'https://www.sub.example.com/x'
            ),
        ],
    )
    await async_validate_path(
        val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
    )


@pytest.mark.asyncio
async def test_permitted_subtrees_intersect_across_intermediates(chain, val_ctx):
    # manual derivation: www.example.com ∈ example.com (ICA-1) but
    # www.example.com ∉ sub.example.com (ICA-2) => intersection empty => reject
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('www.example.com')]
    )
    with pytest.raises(PathValidationError, match='permitted namespace'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )

    # manual derivation: www.other.net ∉ example.com (ICA-1) => reject
    # regardless of what ICA-2 permits
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('www.other.net')]
    )
    with pytest.raises(PathValidationError, match='permitted namespace'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )

    # manual derivation: deep.sub.example.com ∈ example.com ∩ sub.example.com
    # (dNSName constraints extend to arbitrary depth) => accept
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('deep.sub.example.com')]
    )
    await async_validate_path(
        val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
    )


@pytest.mark.asyncio
async def test_dns_label_boundary_enforced_on_chain(chain, val_ctx):
    # manual derivation: evilsub.example.com is a string suffix match for
    # "sub.example.com" but not a label-boundary match => outside ICA-2's
    # permitted subtree => reject
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('evilsub.example.com')]
    )
    with pytest.raises(PathValidationError, match='permitted namespace'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )

    # manual derivation: sub.example.com.evil.net has the permitted domain
    # as a prefix, not as a label-wise suffix => reject
    leaf = _issue_leaf(
        issuer=chain.ica2,
        san=[crypto_x509.DNSName('sub.example.com.evil.net')],
    )
    with pytest.raises(PathValidationError, match='permitted namespace'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )

    # manual derivation: the constraint base itself is permitted
    # (zero labels added) => accept
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('sub.example.com')]
    )
    await async_validate_path(
        val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
    )


