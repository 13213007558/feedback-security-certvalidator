"""
Regression tests for RFC 5280 name constraint propagation across
certification paths with several intermediate CAs.

All certificates are generated at test time (validity window: yesterday
through roughly ten years from now), so these tests never silently depend
on static fixture certificates expiring. If the chain layout changes,
update the diagram below together with the generator code.

Chain diagram (as generated by the ``chain`` fixture)
-----------------------------------------------------

::

    Root CA                          (trust anchor, self-signed)
    ├── ICA-1  CN=Example Corp CA
    │     NC permitted: dNSName example.com | rfc822Name .example.com
    │                   | uniformResourceIdentifier .example.com
    │     NC excluded:  dNSName blocked.sub.example.com
    │   ├── ICA-DNS-ONLY  CN=DNS Only CA
    │   │     NC permitted: dNSName example.com   (no rfc822Name constraint)
    │   ├── ICA-IP  CN=IP CA
    │   │     NC permitted: iPAddress 10.0.0.0/8  (unsupported name type)
    │   ├── ICA-EMPTY  CN=Empty Subtree CA
    │   │     NC permitted: dNSName ""            (empty base: permits nothing)
    │   ├── ICA-EMPTY-EXCL  CN=Empty Excluded CA
    │   │     NC excluded:  dNSName ""            (empty base: excludes nothing)
    │   └── ICA-2  CN=Sub CA
    │         NC permitted: dNSName sub.example.com | rfc822Name sub.example.com
    │         NC excluded:  dNSName bad.sub.example.com
    │                       | rfc822Name badactor@sub.example.com
    │         └── ICA-2'  CN=Sub CA   (self-issued re-key of ICA-2: same
    │             SAN: dNSName rogue.example.org   subject name, different key,
    │             NC permitted: dNSName deep.sub.example.com    NOT self-signed)
    │             └── Leaf

Every expected verdict in this file is derived by hand from the constraint
relations above (see the comments next to each assertion); none of the
expectations are produced by running the validator under test.
"""

