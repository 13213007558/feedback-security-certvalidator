@pytest.mark.asyncio
async def test_excluded_subtree_overrides_permitted(chain, val_ctx):
    # manual derivation: bad.sub.example.com ∈ permitted intersection
    # (example.com ∩ sub.example.com) but ∈ excluded bad.sub.example.com
    # at ICA-2 => reject; excluded always wins over permitted
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('bad.sub.example.com')]
    )
    with pytest.raises(PathValidationError, match='excluded'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )

    # manual derivation: blocked.sub.example.com is excluded at ICA-1, one
    # level above ICA-2's permitted sub.example.com; excluded subtrees from
    # all generations accumulate (union) => still rejected at the leaf
    leaf = _issue_leaf(
        issuer=chain.ica2,
        san=[crypto_x509.DNSName('blocked.sub.example.com')],
    )
    with pytest.raises(PathValidationError, match='excluded'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )

    # manual derivation: badactor@sub.example.com ∈ permitted
    # (.example.com ∩ sub.example.com) but matches the excluded mailbox
    # exactly => reject; any other mailbox at the same host is fine
    leaf = _issue_leaf(
        issuer=chain.ica2,
        san=[crypto_x509.RFC822Name('badactor@sub.example.com')],
    )
    with pytest.raises(PathValidationError, match='excluded'):
        await async_validate_path(
            val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
        )
    leaf = _issue_leaf(
        issuer=chain.ica2,
        san=[crypto_x509.RFC822Name('other@sub.example.com')],
    )
    await async_validate_path(
        val_ctx, chain.path(leaf, [chain.ica1, chain.ica2])
    )


