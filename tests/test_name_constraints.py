@pytest.mark.asyncio
async def test_mutation_union_instead_of_intersection(chain, val_ctx, monkeypatch):
    # Sample: www.example.com is permitted by ICA-1's generation but not by
    # ICA-2's. Correct (intersection) semantics reject it.
    leaf = _issue_leaf(
        issuer=chain.ica2, san=[crypto_x509.DNSName('www.example.com')]
    )
    path = chain.path(leaf, [chain.ica1, chain.ica2])
    with pytest.raises(PathValidationError, match='permitted namespace'):
        await async_validate_path(val_ctx, path)

    # Seeded mutation: accept a name if ANY generation accepts it (union)
    # instead of requiring ALL generations to accept it (intersection).
    def union_accept_name(self, name_type, name):
        try:
            return any(
                any(name in tree for tree in trees_in_generation)
                for trees_in_generation in self._trees[name_type]
            )
        except NameConstraintError:
            return False

    monkeypatch.setattr(
        name_trees.PermittedSubtrees, 'accept_name', union_accept_name
    )
    # If the mutation goes unnoticed (i.e. this call raises), the tests
    # above are not sensitive to intersection semantics.
    await async_validate_path(val_ctx, path)


@pytest.mark.asyncio
async def test_mutation_dropped_excluded_entry(chain, val_ctx, monkeypatch):
    # Sample: badactor@sub.example.com is excluded by an rfc822Name entry
    # at ICA-2. Correct semantics reject the leaf.
    leaf = _issue_leaf(
        issuer=chain.ica2,
        san=[crypto_x509.RFC822Name('badactor@sub.example.com')],
    )
    path = chain.path(leaf, [chain.ica1, chain.ica2])
    with pytest.raises(PathValidationError, match='excluded'):
        await async_validate_path(val_ctx, path)

    # Seeded mutation: silently drop rfc822Name entries when merging
    # excluded subtrees (i.e. "forget" one excluded item).
    def lax_union_with(self, trees):
        for name_type, new_excluded in trees.items():
            if name_type is GeneralNameType.RFC822_NAME:
                continue
            self._trees[name_type].update(new_excluded)

    monkeypatch.setattr(
        name_trees.ExcludedSubtrees, 'union_with', lax_union_with
    )
    # If the mutation goes unnoticed (i.e. this call raises), the excluded
    # subtree tests are not sensitive to dropped entries.
    await async_validate_path(val_ctx, path)
