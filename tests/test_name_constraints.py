NOT_BEFORE = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(
    days=1
)
NOT_AFTER = NOT_BEFORE + datetime.timedelta(days=3650)


# ---------------------------------------------------------------------------
# Certificate generation helpers
# ---------------------------------------------------------------------------


def _new_key():
    return ec.generate_private_key(ec.SECP256R1())


def _dn(cn: Optional[str] = None, email: Optional[str] = None):
    attrs = []
    if cn is not None:
        attrs.append(crypto_x509.NameAttribute(NameOID.COMMON_NAME, cn))
    if email is not None:
        attrs.append(crypto_x509.NameAttribute(NameOID.EMAIL_ADDRESS, email))
    return crypto_x509.Name(attrs)


@dataclass
class Issued:
    crypto: crypto_x509.Certificate
    asn1: asn1_x509.Certificate
    key: object


def _issue(
    *,
    subject,
    issuer: Optional[Issued],
    subject_key,
    ca: bool,
    san: Optional[Sequence] = None,
    name_constraints: Optional[crypto_x509.NameConstraints] = None,
) -> Issued:
    builder = crypto_x509.CertificateBuilder()
    builder = builder.subject_name(subject)
    builder = builder.issuer_name(
        issuer.crypto.subject if issuer is not None else subject
    )
    builder = builder.public_key(subject_key.public_key())
    builder = builder.serial_number(crypto_x509.random_serial_number())
    builder = builder.not_valid_before(NOT_BEFORE)
    builder = builder.not_valid_after(NOT_AFTER)
    builder = builder.add_extension(
        crypto_x509.BasicConstraints(ca=ca, path_length=None), critical=True
    )
    builder = builder.add_extension(
        crypto_x509.KeyUsage(
            digital_signature=not ca,
            content_commitment=False,
            key_encipherment=False,
            data_encipherment=False,
            key_agreement=False,
            key_cert_sign=ca,
            crl_sign=ca,
            encipher_only=False,
            decipher_only=False,
        ),
        critical=True,
    )
    builder = builder.add_extension(
        crypto_x509.SubjectKeyIdentifier.from_public_key(
            subject_key.public_key()
        ),
        critical=False,
    )
    issuer_pub = (
        issuer.key.public_key() if issuer is not None else subject_key.public_key()
    )
    builder = builder.add_extension(
        crypto_x509.AuthorityKeyIdentifier.from_issuer_public_key(issuer_pub),
        critical=False,
    )
    if san is not None:
        builder = builder.add_extension(
            crypto_x509.SubjectAlternativeName(list(san)), critical=False
        )
    if name_constraints is not None:
        builder = builder.add_extension(name_constraints, critical=True)
    signing_key = issuer.key if issuer is not None else subject_key
    crypto_cert = builder.sign(signing_key, hashes.SHA256())
    return Issued(
        crypto=crypto_cert,
        asn1=asn1_x509.Certificate.load(crypto_cert.public_bytes(Encoding.DER)),
        key=subject_key,
    )


def _issue_ca(*, cn, issuer, san=None, name_constraints=None) -> Issued:
    return _issue(
        subject=_dn(cn),
        issuer=issuer,
        subject_key=_new_key(),
        ca=True,
        san=san,
        name_constraints=name_constraints,
    )


def _issue_leaf(*, issuer: Issued, subject=None, san=None) -> Issued:
    return _issue(
        subject=subject if subject is not None else _dn('leaf'),
        issuer=issuer,
        subject_key=_new_key(),
        ca=False,
        san=san,
    )


@dataclass
class Chain:
    root: Issued
    ica1: Issued
    ica2: Issued
    ica2_rekeyed: Issued
    ica_dns_only: Issued
    ica_ip: Issued
    ica_empty: Issued
    ica_empty_excl: Issued

    def path(self, leaf: Issued, interm: List[Issued]) -> ValidationPath:
        return ValidationPath(
            trust_anchor=CertTrustAnchor(self.root.asn1),
            interm=[c.asn1 for c in interm],
            leaf=leaf.asn1,
        )


